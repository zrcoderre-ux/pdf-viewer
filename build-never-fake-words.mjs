// Builds viewer/never-fake-words.js from PDF-Linker's never-fake list, so the
// reader fakes a key's one-word real the way PDF-Linker does: only where it is
// capitalised (pseudo-key.js, capOnlyReal).
//
// Run: node build-never-fake-words.mjs ["<PDF-Linker>/Word Lists/Never Fake Words.txt"]
//      (from the repo root; the file defaults to ../PDF-Linker/Word Lists/,
//      the two checkouts side by side). It copies the list to "Never Fake
//      Words.txt" here and writes the module from it. Run it again whenever
//      PDF-Linker regenerates the list (`_pn_write_never_fake_words`), and
//      commit both. test-never-fake-words.mjs fails while the module and the
//      copy disagree, or the copy and the list beside this checkout do.

import { readFileSync, writeFileSync } from "fs";
import { dirname, join, resolve } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));

// Run as a script (the test imports moduleFor and writes nothing).
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const src = process.argv[2] || join(here, "..", "PDF-Linker", "Word Lists", "Never Fake Words.txt");
  const text = readFileSync(src, "utf8");
  writeFileSync(join(here, "Never Fake Words.txt"), text);
  writeFileSync(join(here, "viewer", "never-fake-words.js"), moduleFor(text));
  console.log(`wrote viewer/never-fake-words.js (${wordsOf(text).length} words)`);
}

export function wordsOf(text) {
  return text.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
}

export function moduleFor(text) {
  const words = wordsOf(text);
  return (
    "// never-fake-words.js — GENERATED by build-never-fake-words.mjs from\n" +
    "// PDF-Linker's Word Lists/Never Fake Words.txt; do not edit.\n" +
    "//\n" +
    "// PDF-Linker's words that are not faked standing alone: a one-word real on\n" +
    "// this list is faked only where it is capitalised (pseudo-key.js). The\n" +
    "// English words are SCOWL's; its notice is PDF-Linker's Word Lists/SCOWL\n" +
    "// Copyright.txt.\n\n" +
    `export const NEVER_FAKE_COUNT = ${words.length};\n\n` +
    `const WORDS = ${JSON.stringify(words.join("\n"))};\n\n` +
    "let set = null;\n\n" +
    "/** Whether `word` (any case) is on the list. The set is built on first use. */\n" +
    "export function isNeverFakeWord(word) {\n" +
    "  if (!set) set = new Set(WORDS.split(\"\\n\"));\n" +
    "  return set.has(String(word == null ? \"\" : word).toLowerCase());\n" +
    "}\n"
  );
}
